Exercise _x(
  String id,
  String ko,
  String en,
  List<Muscle> p,
  List<Muscle> s,
  List<Equipment> eq,
  MovementPattern pat,
  _R reps, {
  ExerciseType? type,
  int d = 1,
  int? rest,
  String desc = '',
  List<String>? cues,
  List<String>? mistakes,
  List<String>? cautions,
  Map<JointArea, int>? stress,
  List<String> alts = const [],
  bool assisted = false,
  bool bw = false,
  bool timed = false,
  List<String> refs = const [],
}) {
  final info = _patternInfo[pat]!;
  final t = type ?? (_compoundPatterns.contains(pat) ? ExerciseType.compound : ExerciseType.isolation);
  // 휴식 기본값: 복합 2~3분, 고립 1~2분 (요구사항의 초기 설정값)
  final r = rest ?? (t == ExerciseType.compound ? (reps.$1 <= 8 ? 180 : 120) : 90);
  return Exercise(
    id: id,
    nameKo: ko,
    nameEn: en,
    primary: p,
    secondary: s,
    equipment: eq,
    type: t,
    pattern: pat,
    difficulty: d,
    repMin: reps.$1,
    repMax: reps.$2,
    restSec: r,
    description: desc.isNotEmpty ? desc : '${pat.ko} 패턴의 운동으로 ${p.map((m) => m.ko).join('·')}을(를) 주로 자극합니다.',
    cues: cues ?? info.cues,
    mistakes: mistakes ?? info.mistakes,
    cautions: cautions ?? info.cautions,
    jointStress: stress ?? info.stress,
    alternatives: alts,
    assisted: assisted,
    bodyweight: bw,
    timed: timed,
    referenceIds: refs,
  );
}

